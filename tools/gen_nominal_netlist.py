#!/usr/bin/env python3
"""Generate the canonical Tortoise v1.0 nominal-die netlist, docs/rev10_1_nominal.cir.

What it is: the Variant 3 die at the `fitc10` nominal corner, weights rev10/eval/F_hw_m4_firstpass.npy, built by the
same call every campaign uses (results/fitc10_campaign/scripts/common.py::build(variant=3); energy_host eh.build and
weights_schemeA wcommon.build reproduce it byte for byte). Input: test sample #81 (label class 5). Warm start: the
Variant 3 fitc10 warm state (results/fitc10_campaign/raw/v3/warmstart/fitc10_warm). The host stimuli in this file are
the v1 (warm-start, 2500 us window) protocol; the v2.1 stimuli are generated by results/host_v21/scripts/hv21.py on
top of the same die (see docs/SPEC.md §4).

Usage (from a fresh clone, after `sh tools/setup_layout.sh`):
    python3 tools/gen_nominal_netlist.py            # writes docs/rev10_1_nominal.cir
    python3 tools/gen_nominal_netlist.py --check    # rebuilds to a scratch file and compares with the committed one
Nothing is simulated. The netlist uses relative includes (../models/...), so it runs from a directory one level
below /home/claude/w/sim (e.g. /home/claude/w/sim/circuits).
"""
import hashlib, os, pathlib, sys

REPO = pathlib.Path(__file__).resolve().parents[1]
sys.dont_write_bytecode = True
sys.path.insert(0, str(REPO / "results/fitc10_campaign/scripts"))
import common as C  # noqa: E402  (imports the frozen builder rev10/sim/tools/build_A.py via /home/claude/w)

IDX = 81
PRIOR = REPO / "results/fitc10_campaign/raw/v3/warmstart/fitc10_warm"
OUT = REPO / "docs/rev10_1_nominal.cir"


def main():
    check = "--check" in sys.argv[1:]
    wd = C.workdir("rev10_1_gen")                      # /home/claude/w/sim/rev10_1_gen (outside the repo)
    dst = wd / "rev10_1_nominal.cir"
    b = C.build(dst, idx=IDX, prior=PRIOR, variant=3)
    text = dst.read_bytes()
    sha = hashlib.sha256(text).hexdigest()
    n_tft = sum(1 for l in text.decode().splitlines() if l.startswith("X"))
    print(f"built sample #{IDX}, Variant 3, tC2 = {b['tC2']} us, {n_tft} TFT instances, sha256 {sha}")
    if check:
        same = OUT.exists() and OUT.read_bytes() == text
        print("committed netlist", "IDENTICAL" if same else "DIFFERS", f"({OUT.relative_to(REPO)})")
        sys.exit(0 if same else 1)
    OUT.write_bytes(text)
    print("wrote", OUT.relative_to(REPO))


if __name__ == "__main__":
    main()
